def main():
    raw = base64.b64decode("".join(DATA.split()))
    if hashlib.sha256(raw).hexdigest() != SHA256:
        sys.exit("bootstrap: bundle is corrupted (checksum mismatch). Re-upload bootstrap.py.")
    here = os.path.dirname(os.path.abspath(__file__))
    with zipfile.ZipFile(io.BytesIO(raw)) as z:
        for name in z.namelist():
            target = os.path.realpath(os.path.join(here, name))
            if not target.startswith(here + os.sep):
                sys.exit("bootstrap: unsafe path in bundle")
        z.extractall(here)
        print(f"bootstrap: extracted {len(z.namelist())} files")


if __name__ == "__main__":
    main()
